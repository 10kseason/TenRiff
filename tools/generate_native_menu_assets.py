"""Original vector artwork for TenRiff's native menu. Python standard library only.

One geometry source exports editable SVGs and a compiled C++ atlas, so packaged
clients need no loose files, image decoders, network requests or working directory.
Run --check to detect stale generated files without changing anything.
"""
import argparse
