ROOT = Path(__file__).resolve().parents[1]
# 100 x 100 local coordinates; each polyline carries its own color and fill mode.
# Studio symbols use one 100-unit grid and the same optical stroke weight.
# Legacy names remain available to imported skins. New option symbols describe
# the action itself: lanes, key mapping, swatches, a timer, a person and a check.
INK = "ECF6FF"

def line(*points):
    return (INK, False, list(points))

def solid(*points):
    return (INK, True, list(points))

def box(left, top, right, bottom):
    return line((left, top), (right, top), (right, bottom), (left, bottom), (left, top))

