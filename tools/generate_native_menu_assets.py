def outputs():
    points, paths, ranges = [], [], []
    files = {}
    for name, shapes in ASSETS.items():
        first = len(paths)
        svg = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">',
               f'  <title>TenRiff native menu - {name}</title>']
        for color, filled, vertices in shapes:
            paths.append((len(points), len(vertices), color, filled))
            points.extend(vertices)
            tag = 'polygon' if filled else 'polyline'
            svg.append(f'  <{tag} points="' + ' '.join(f'{x},{y}' for x, y in vertices) +
                       f'" fill="{"#" + color if filled else "none"}" stroke="#{color}" '
                       'stroke-width="2.16" stroke-linejoin="miter" stroke-linecap="butt"/>')
        svg.append('</svg>')
        files[ROOT / 'assets' / 'native-menu' / (name.lower() + '.svg')] = '\n'.join(svg) + '\n'
        ranges.append((name, first, len(shapes)))
    header = ['// Generated by tools/generate_native_menu_assets.py. Edit the generator.', '#pragma once',
              '#include <array>', '#include <cstdint>', 'namespace tenriff::render::native_menu_assets {',
              'struct Point { float x, y; };',
              'struct Path { unsigned first, count; uint32_t color; bool filled; };',
              'struct Asset { unsigned first, count; };',
              f'inline constexpr std::array<Point, {len(points)}> points{{{{']
    header += [f'    {{{x}.0f, {y}.0f}},' for x, y in points]
    header += ['}};', f'inline constexpr std::array<Path, {len(paths)}> paths{{{{']
    header += [f'    {{{first}, {count}, 0x{color}, {str(filled).lower()}}},' for first, count, color, filled in paths]
    header += ['}};'] + [f'inline constexpr Asset k{name}{{{first}, {count}}};' for name, first, count in ranges]
    header += ['} // namespace tenriff::render::native_menu_assets', '']
    files[ROOT / 'src' / 'render' / 'NativeMenuAssets.h'] = '\n'.join(header)
    return files

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
    if stale:
        raise SystemExit('Stale native menu assets: ' + ', '.join(stale))
    print(f'Native menu atlas: {len(ASSETS)} assets; {"verified" if args.check else "generated"}.')

if __name__ == '__main__':
    main()
